void zr_gfx_begin(uint16_t *buf, unsigned y0, unsigned h)
{
    g_buf = buf;
    g_y0 = (int)y0;
    g_y1 = (int)(y0 + h);
}
void zr_fill(int x, int y, int w, int h, uint16_t c)
{
    if (!g_buf) return;
    int x1 = x + w, y1 = y + h;
    if (x < 0) x = 0;
    if (x1 > ZR_SCREEN_W) x1 = ZR_SCREEN_W;
    if (y < g_y0) y = g_y0;
    if (y1 > g_y1) y1 = g_y1;
    for (; y < y1; ++y) {
        uint16_t *row = g_buf + (y - g_y0) * ZR_SCREEN_W;
        for (int i = x; i < x1; ++i) row[i] = c;
    }
}
void zr_frame(int x, int y, int w, int h, uint16_t c)
{
    zr_fill(x, y, w, 1, c);
    zr_fill(x, y + h - 1, w, 1, c);
    zr_fill(x, y, 1, h, c);
    zr_fill(x + w - 1, y, 1, h, c);
}
static void pixel(int x, int y, uint16_t c)
{
    if (x >= 0 && x < ZR_SCREEN_W && y >= g_y0 && y < g_y1) g_buf[(y - g_y0) * ZR_SCREEN_W + x] = c;
}
void zr_line(int x0, int y0, int x1, int y1, uint16_t c)
{
    if (!g_buf) return;
    if ((y0 < g_y0 && y1 < g_y0) || (y0 >= g_y1 && y1 >= g_y1)) return;
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, dy = y1 > y0 ? y0 - y1 : y1 - y0;
    int sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1, err = dx + dy;
    for (unsigned guard = 0; guard < 1024; ++guard) {
        pixel(x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}
void zr_arc(int cx, int cy, int r, int a0, int a1, int thick, uint16_t c)
{
    if (!g_buf || r <= 0) return;
    if (cy + r + thick < g_y0 || cy - r - thick >= g_y1) return;
    int step = 4096 / (7 * r) + 1;
    for (int a = a0; a <= a1; a += step) {
        int x = cx + ((r * zr_sin[(a + 1024) & 4095] + 16384) >> 15);
        int y = cy - ((r * zr_sin[a & 4095] + 16384) >> 15);
        zr_fill(x, y, thick, thick, c);
    }
}
int zr_text_width(const char *s, unsigned scale) { return (int)(zr_strlen(s) * 6 * scale); }
int zr_text(int x, int y, const char *s, unsigned scale, uint16_t c)
{
    if (!g_buf || !s) return x;
    int sc = (int)scale;
    if (y >= g_y1 || y + 7 * sc <= g_y0) return x + zr_text_width(s, scale);
    for (; *s; ++s, x += 6 * sc) {
        unsigned ch = (unsigned char)*s;
        if (ch >= 'a' && ch <= 'z') ch -= 32;
        if (ch < 32 || ch > 95) ch = '?';
        const uint8_t *gl = font[ch - 32];
        for (int row = 0; row < 7; ++row) {
            unsigned bits = gl[row];
            if (!bits) continue;
            for (int col = 0; col < 5; ++col)
                if (bits & (0x10u >> col)) zr_fill(x + col * sc, y + row * sc, sc, sc, c);
        }
    }
    return x;
}
void zr_text_center(int cx, int y, const char *s, unsigned scale, uint16_t c)
{
    zr_text(cx - (zr_text_width(s, scale) - (int)scale) / 2, y, s, scale, c);
}
void zr_text_right(int xr, int y, const char *s, unsigned scale, uint16_t c)
{
    zr_text(xr - zr_text_width(s, scale) + (int)scale, y, s, scale, c);
}
