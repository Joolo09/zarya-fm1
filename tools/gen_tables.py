"""Generate core/zr_tables.c: every lookup table of the ZARYA DSP core.

The DSP core is integer-only so that the host tests, the WebAssembly build
and the FM-1 build produce bit-identical audio. All floating point lives
here, at build time. Run: python3 tools/gen_tables.py
"""
import math
import os

SR = 44100.0
CTL = SR / 16.0  # control rate: one tick per 16 samples

out = []


def emit(ctype, name, values, per_line=8, fmt="{}"):
    out.append("ZR_AUDIO_DATA const %s %s[%d] = {" % (ctype, name, len(values)))
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt.format(v) for v in values[i:i + per_line]) + ",")
    out.append("};")
    out.append("")


# Sine, Q15.
emit("int16_t", "zr_sin", [int(round(32767 * math.sin(2 * math.pi * i / 4096))) for i in range(4096)], 12)

# Phase increment per sample for MIDI notes 0..127 (2^32 = one cycle).
emit("uint32_t", "zr_note_inc",
     [int(round(2 ** 32 * 440.0 * 2 ** ((n - 69) / 12.0) / SR)) for n in range(128)], 6, "{}u")

# 2^(i / (256*12)) in Q16: fraction of a semitone in 1/256 steps.
emit("uint32_t", "zr_frac", [int(round(65536 * 2 ** (i / (256.0 * 12.0)))) for i in range(256)], 8, "{}u")

# Operator level: 0.75 dB per step, 127 = 0 dB, 0 = silence. Q15.
emit("uint16_t", "zr_level",
     [0] + [int(round(32767 * 10 ** (-(127 - i) * 0.75 / 20.0))) for i in range(1, 128)], 10)

# Square-law volume for velocity, track level and sends. Q15.
emit("uint16_t", "zr_vol", [int(round(32767 * (i / 127.0) ** 2)) for i in range(128)], 10)

# Envelope RC coefficient per control tick, Q24. 0 = 1 ms ... 127 = 12 s.
rates = []
for i in range(128):
    tau = 0.001 * (12000.0 ** (i / 127.0))
    rates.append(int(round((1.0 - math.exp(-1.0 / (tau * CTL))) * (1 << 24))))
emit("uint32_t", "zr_env_rate", rates, 6, "{}u")

# Chamberlin SVF frequency coefficient, 2x oversampled, Q14. 20 Hz .. 14.5 kHz.
cut = []
for i in range(128):
    fc = min(20.0 * 2 ** (i / 127.0 * 9.6), 14500.0)
    cut.append(int(round(2.0 * math.sin(math.pi * fc / (2.0 * SR)) * (1 << 14))))
emit("uint16_t", "zr_cutoff", cut, 10)

# LFO phase increment per control tick. 0.05 Hz .. 30 Hz.
emit("uint32_t", "zr_lfo_rate",
     [int(round(2 ** 32 * (0.05 * (600.0 ** (i / 127.0))) / CTL)) for i in range(128)], 6, "{}u")

# Operator frequency ratios, Q12: 0.5, 1 .. 16.
emit("uint32_t", "zr_ratio", [2048] + [4096 * r for r in range(1, 17)], 9, "{}u")

header = """/* SPDX-License-Identifier: GPL-3.0-only WITH GPL-3.0-linking-exception */
/* GENERATED by tools/gen_tables.py. Do not edit. */
#include "zr_dsp.h"
"""
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "zr_tables.c")
with open(path, "w") as f:
    f.write(header + "\n" + "\n".join(out))
print("wrote", os.path.normpath(path))
